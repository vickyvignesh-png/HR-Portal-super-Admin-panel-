import React, { useState, useEffect } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import { jsPDF } from 'jspdf';
import {
  Printer,
  Download,
  ArrowLeft,
  ReceiptIndianRupee,
  Building2,
  CheckCircle,
  FileCheck2
} from 'lucide-react';
import { PageHeader } from '../../components/layout/PageHeader';
import { StatusBadge } from '../../components/common/StatusBadge';
import { Button } from '../../components/common/Button';
import { storageService } from '../../services/storageService';
import { useToast } from '../../context/ToastContext';
import { formatCurrency, formatDate } from '../../utils/formatters';
import '../../styles/billing.css';

export const InvoiceDetails = () => {
  const { id } = useParams();
  const navigate = useNavigate();
  const { addToast } = useToast();

  const [payment, setPayment] = useState(null);
  const [company, setCompany] = useState(null);

  useEffect(() => {
    const p = storageService.getPaymentById(id);
    if (p) {
      setPayment(p);
      const c = storageService.getCompanyById(p.companyId);
      setCompany(c);
    }
  }, [id]);

  if (!payment) {
    return (
      <div className="card">
        <div className="empty-state">
          <h3>Invoice Not Found</h3>
          <p>No billing invoice associated with payment ID {id}.</p>
          <Button variant="primary" onClick={() => navigate('/billing')}>
            Return to Billing
          </Button>
        </div>
      </div>
    );
  }

  const handlePrint = () => {
    window.print();
  };

  const handleDownloadPDF = () => {
    try {
      const doc = new jsPDF();
      
      doc.setFontSize(20);
      doc.setTextColor(37, 99, 235);
      doc.text('HR PORTAL — TAX INVOICE', 14, 22);

      doc.setFontSize(10);
      doc.setTextColor(100, 116, 139);
      doc.text('Super Admin Billing Department (Demonstration)', 14, 28);
      doc.text(`Invoice No: ${payment.invoiceNumber}`, 14, 34);
      doc.text(`Invoice Date: ${formatDate(payment.invoiceDate)}`, 14, 40);
      doc.text(`Payment Status: ${payment.status}`, 14, 46);

      doc.setDrawColor(226, 232, 240);
      doc.line(14, 52, 196, 52);

      // Billed To
      doc.setFontSize(11);
      doc.setTextColor(15, 23, 42);
      doc.text('BILLED TO:', 14, 60);
      doc.text(payment.companyName, 14, 66);
      doc.setFontSize(9);
      doc.setTextColor(100, 116, 139);
      doc.text(`Tenant ID: ${payment.companyId}`, 14, 72);
      doc.text(`GSTIN: ${company?.gstNumber || 'N/A'}`, 14, 78);
      doc.text(`Address: ${company?.registeredAddress || '100 Silicon Blvd'}, ${company?.city || 'San Jose'}`, 14, 84);

      // Table Header
      doc.setFillColor(241, 245, 249);
      doc.rect(14, 94, 182, 8, 'F');
      doc.setFontSize(10);
      doc.setTextColor(15, 23, 42);
      doc.text('Description', 18, 100);
      doc.text('Amount (INR)', 160, 100);

      // Row
      doc.text('Subscription Plan Licensing & Platform Cloud Hosting', 18, 110);
      doc.text(`INR ${payment.amount.toFixed(2)}`, 160, 110);

      doc.line(14, 118, 196, 118);

      // Totals
      doc.setFontSize(9);
      doc.text(`Subtotal: INR ${payment.amount.toFixed(2)}`, 140, 126);
      doc.text(`Promotional Discount: -INR ${payment.discount.toFixed(2)}`, 140, 132);
      doc.text(`Estimated Tax (18%): +INR ${payment.tax.toFixed(2)}`, 140, 138);

      doc.setFontSize(11);
      doc.setTextColor(37, 99, 235);
      const totalCalc = payment.amount - payment.discount + payment.tax;
      doc.text(`Total Settled: INR ${totalCalc.toFixed(2)}`, 140, 148);

      // Footer
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text('This is a simulated demonstration invoice generated by the HR Portal Super Admin.', 14, 180);

      doc.save(`${payment.invoiceNumber}.pdf`);

      addToast({
        type: 'success',
        title: 'PDF Downloaded',
        message: `Saved ${payment.invoiceNumber}.pdf to your device.`
      });
    } catch (err) {
      console.error(err);
      addToast({
        type: 'error',
        title: 'PDF Generation Error',
        message: 'Could not generate PDF directly. Please use the Print option.'
      });
    }
  };

  const totalAmount = payment.amount - payment.discount + payment.tax;

  return (
    <div className="dashboard-container">
      <div className="no-print">
        <PageHeader
          title={`Invoice ${payment.invoiceNumber}`}
          description={`Payment ID: ${payment.id} • Order: ${payment.orderId}`}
          badge={<StatusBadge status={payment.status} />}
          actions={
            <div className="flex gap-2">
              <Button
                variant="secondary"
                icon={ArrowLeft}
                onClick={() => navigate('/billing')}
              >
                Back to Billing
              </Button>
              <Button
                variant="secondary"
                icon={Printer}
                onClick={handlePrint}
              >
                Print Invoice
              </Button>
              <Button
                variant="primary"
                icon={Download}
                onClick={handleDownloadPDF}
              >
                Download PDF
              </Button>
            </div>
          }
        />
      </div>

      <div className="invoice-card" id="invoice-printable-area">
        <div className="invoice-header-row">
          <div>
            <div className="flex items-center gap-2 mb-2">
              <div className="brand-icon-wrapper">
                <ReceiptIndianRupee size={20} />
              </div>
              <h2 className="invoice-title">HR PORTAL</h2>
            </div>
            <p className="text-muted">Enterprise Cloud Platform Services</p>
            <p className="text-muted">Super Admin Financial Ops</p>
          </div>

          <div className="invoice-meta-info">
            <h3 className="invoice-title">{payment.invoiceNumber}</h3>
            <span className="text-secondary">Date: {formatDate(payment.invoiceDate)}</span>
            <span className="text-secondary">Gateway: {payment.gateway}</span>
            <span className="text-secondary">Ref: {payment.transactionId}</span>
            <div className="mt-1">
              <StatusBadge status={payment.status} />
            </div>
          </div>
        </div>

        <div className="invoice-parties">
          <div className="party-box">
            <span className="party-title">Billed To</span>
            <span className="font-bold text-primary">{payment.companyName}</span>
            <span className="text-secondary">{company?.registeredAddress || '100 Silicon Blvd, Suite 400'}</span>
            <span className="text-secondary">{company?.city || 'San Jose'}, {company?.state || 'CA'}</span>
            <span className="text-secondary">GSTIN: {company?.gstNumber || '06AAACA9823P1Z5'}</span>
            <span className="text-secondary">Official Email: {company?.email || 'finance@company.example.com'}</span>
          </div>

          <div className="party-box">
            <span className="party-title">Payment Settlement</span>
            <span className="text-secondary">Method: {payment.method}</span>
            <span className="text-secondary">Subscription: {payment.subscriptionId}</span>
            <span className="text-secondary">Settled: {formatDate(payment.paymentDate)}</span>
          </div>
        </div>

        <table className="invoice-items-table">
          <thead>
            <tr>
              <th>Description</th>
              <th>Billing Term</th>
              <th>Unit Rate</th>
              <th>Total</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>
                <div className="font-semibold text-primary">HR Portal Enterprise Tier Subscription</div>
                <div className="text-muted">Candidate alert feeds, resume sourcing unlocks, applicant tracking infrastructure</div>
              </td>
              <td>1 Month</td>
              <td>{formatCurrency(payment.amount)}</td>
              <td className="font-semibold">{formatCurrency(payment.amount)}</td>
            </tr>
          </tbody>
        </table>

        <div className="invoice-summary-box">
          <div className="summary-row">
            <span>Subtotal</span>
            <span>{formatCurrency(payment.amount)}</span>
          </div>
          {payment.discount > 0 && (
            <div className="summary-row">
              <span>Promotional Credit</span>
              <span className="text-success">-{formatCurrency(payment.discount)}</span>
            </div>
          )}
          <div className="summary-row">
            <span>Tax (18% GST/VAT)</span>
            <span>+{formatCurrency(payment.tax)}</span>
          </div>
          <div className="summary-row total">
            <span>Total Amount Paid</span>
            <span className="text-blue">{formatCurrency(totalAmount)}</span>
          </div>
        </div>

        <div className="simulation-note mt-8">
          <strong>Notice:</strong> This is a browser demonstration invoice rendered by the Super Admin frontend. No external financial transaction was processed.
        </div>
      </div>
    </div>
  );
};
